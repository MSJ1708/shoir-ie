-- Server-side, append-only audit events for verified OIDC authentication.
-- The table intentionally has no browser-role policies or privileges.
CREATE TABLE IF NOT EXISTS public.shoir_security_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL CHECK (
        length(event_type) BETWEEN 1 AND 64
        AND event_type ~ '^[a-z][a-z0-9_.-]*$'
    ),
    outcome TEXT NOT NULL CHECK (outcome IN ('success', 'denied', 'expired', 'error')),
    actor_username_lc TEXT,
    provider_issuer TEXT,
    subject_sha256 TEXT CHECK (
        subject_sha256 IS NULL OR subject_sha256 ~ '^[0-9a-f]{64}$'
    ),
    id_token_sha256 TEXT UNIQUE CHECK (
        id_token_sha256 IS NULL OR id_token_sha256 ~ '^[0-9a-f]{64}$'
    ),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    details JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object')
);

-- The idempotent CREATE above must not silently accept a table with the wrong contract.
DO $migration$
DECLARE
    expected_columns TEXT[] := ARRAY[
        'id', 'event_type', 'outcome', 'actor_username_lc', 'provider_issuer',
        'subject_sha256', 'id_token_sha256', 'occurred_at', 'details'
    ];
    actual_columns TEXT[];
BEGIN
    SELECT array_agg(column_name::TEXT ORDER BY ordinal_position)
      INTO actual_columns
      FROM information_schema.columns
     WHERE table_schema = 'public'
       AND table_name = 'shoir_security_audit_events';

    IF actual_columns IS NULL
       OR NOT expected_columns <@ actual_columns
    THEN
        RAISE EXCEPTION 'shoir_security_audit_events does not match the required audit schema';
    END IF;
END;
$migration$;

ALTER TABLE public.shoir_security_audit_events ENABLE ROW LEVEL SECURITY;

-- Remove any prior/default access and grant the Edge Function the minimum required write path.
REVOKE ALL ON TABLE public.shoir_security_audit_events
    FROM PUBLIC, anon, authenticated, service_role;
GRANT INSERT ON TABLE public.shoir_security_audit_events TO service_role;

REVOKE ALL ON SEQUENCE public.shoir_security_audit_events_id_seq
    FROM PUBLIC, anon, authenticated, service_role;
GRANT USAGE ON SEQUENCE public.shoir_security_audit_events_id_seq TO service_role;

-- Intentionally no SELECT, UPDATE or DELETE grants to API roles.
COMMIT;
