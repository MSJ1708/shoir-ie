def _known_tier(value: str) -> str | None:
    """Normalize known package labels while rejecting unknown values fail-closed."""
    raw = str(value or "").strip().casefold()
    if not raw:
        return None
    if "research" in raw:
        return "Research Pack"
    if "enterprise plus" in raw or "industrial enterprise" in raw:
        return "Enterprise Plus"
    if "enterprise" in raw:
        return "Enterprise"
    if "professional" in raw:
        return "Professional"
    if "mid-tier pro" in raw or "mid tier pro" in raw or raw == "pro" or "pro tier" in raw:
        return "Mid-Tier Pro"
    if "starter" in raw:
        return "Starter"
    return None


def tool_access_allowed(tier: str, tool_id: str) -> bool:
    """Return False for unknown tiers/IDs and enforce the separate Research Pack rules."""
    spec = TOOL_BY_ID.get(str(tool_id or "").strip().upper())
    current = _known_tier(tier)
    if spec is None or current is None:
        return False
    required = spec.get("minimum_tier")
    if required not in {"Starter", "Mid-Tier Pro", "Professional", "Enterprise", "Enterprise Plus", "Research Pack"}:
        return False
    return tier_allows(current, required)


def visible_tools(
    tier: str,
    *,
    workbench: str | None = None,
    query: str = "",
    include_locked: bool = True,
) -> list[dict[str, Any]]:
    """Return catalog rows with a computed access flag; never changes the source entries."""
    text_query = str(query or "").strip().casefold()
    result: list[dict[str, Any]] = []
    for source in TOOL_CATALOG:
        if workbench and source["workbench"] != workbench:
            continue
        if text_query and not any(
            text_query in str(source.get(key, "")).casefold()
            for key in ("tool_id", "canonical_name", "workbench", "summary", "existing_route")
        ):
            continue
        allowed = tool_access_allowed(tier, source["tool_id"])
        if not include_locked and not allowed:
            continue
        item = dict(source)
        item["accessible"] = allowed
        result.append(item)
    return result


def validate_tool_catalog(rows: Iterable[dict[str, Any]] | None = None) -> list[str]:
    """Return invariant errors for CI; an empty list means catalog shape is valid."""
    items = list(TOOL_CATALOG if rows is None else rows)
    errors: list[str] = []
    ids = [str(x.get("tool_id", "")) for x in items]
    names = [str(x.get("canonical_name", "")) for x in items]
    expected = {f"T{i:03d}" for i in range(1, 101)}
    if len(items) != 100:
        errors.append(f"expected exactly 100 catalog rows, found {len(items)}")
    if len(ids) != len(set(ids)):
        errors.append("tool_id values must be unique")
    if set(ids) != expected:
        errors.append(f"tool_id set mismatch: missing={sorted(expected-set(ids))}, extra={sorted(set(ids)-expected)}")
    if len(names) != len(set(names)):
        errors.append("canonical tool names must be unique")
    valid_tiers = {"Starter", "Mid-Tier Pro", "Professional", "Enterprise", "Enterprise Plus", "Research Pack"}
    for item in items:
        tid = str(item.get("tool_id", "<missing>"))
        if not str(item.get("canonical_name", "")).strip():
            errors.append(f"{tid}: canonical_name is empty")
        if not str(item.get("workbench", "")).strip():
            errors.append(f"{tid}: workbench is empty")
        if item.get("minimum_tier") not in valid_tiers:
            errors.append(f"{tid}: invalid minimum_tier {item.get('minimum_tier')!r}")
        if item.get("implementation_status") not in VALID_IMPLEMENTATION_STATUSES:
            errors.append(f"{tid}: invalid implementation_status {item.get('implementation_status')!r}")
        if not str(item.get("input_contract", "")).strip():
            errors.append(f"{tid}: input_contract is empty")
        if not str(item.get("output_contract", "")).strip():
            errors.append(f"{tid}: output_contract is empty")
        if item.get("implementation_status") == "VERIFIED_WORKING" and (
            item.get("browser_test") != "PASS" or item.get("integration_test") != "PASS"
        ):
            errors.append(f"{tid}: VERIFIED_WORKING requires explicit browser and integration PASS evidence")
    return errors
